#!/usr/bin/env python3
"""lcd_font_pkg.vhd from Zephyr's 10x16 monospace font (subsys/fb/cfb_fonts.c, cfb_font_1016).
    python3 make_lcd_font.py <zephyr>/subsys/fb/cfb_fonts.c > lcd_font_pkg.vhd

The font there is vertically packed: per character 10 columns of two bytes, the first byte rows
0..7 and the second rows 8..15, the least significant bit the top. Here it is turned to rows:
the ROM's word (c - 32) * 16 + row holds that row's 10 pixels, bit 9 the leftmost.
"""
import re
import sys

text = open(sys.argv[1]).read()
body = text[text.index('cfb_font_1016'):]
body = body[:body.index('};')]
glyphs = [[int(v, 16) for v in re.findall(r'0x([0-9a-fA-F]{2})', g)]
          for g in re.findall(r'\{([^{}]*)\}', body)]
assert len(glyphs) == 95 and all(len(g) == 20 for g in glyphs), (len(glyphs), set(map(len, glyphs)))

words = []
for g in glyphs:
    columns = [g[2 * c] | g[2 * c + 1] << 8 for c in range(10)]
    for row in range(16):
        words.append(sum(((columns[c] >> row) & 1) << (9 - c) for c in range(10)))

print('''-- Generated by make_lcd_font.py from Zephyr's subsys/fb/cfb_fonts.c (cfb_font_1016), which
-- was generated from the font DroidSansMono.ttf:
--   Copyright (c) 2018 PHYTEC Messtechnik GmbH
--   Copyright (C) 2008 The Android Open Source Project
--   Licensed under the Apache License, Version 2.0 (http://www.apache.org/licenses/LICENSE-2.0)
-- Changed: the glyphs turned from columns to rows.
--
-- The characters 32 .. 126, 10 x 16 pixels: word (c - 32) * 16 + row holds the row's pixels, bit
-- 9 the leftmost. 2048 words, the ones after the last character zero.
library ieee;
    use ieee.std_logic_1164.all;

    use work.dual_port_ram_pkg.all;

package lcd_font_pkg is

    constant lcd_font_width  : natural := 10;
    constant lcd_font_height : natural := 16;
    constant lcd_font_first  : natural := 32;
    constant lcd_font_last   : natural := 126;

    constant lcd_font : ram_array(0 to 2047)(9 downto 0) := (''')
lines = []
for i in range(0, len(words), 8):
    lines.append('        ' + ', '.join(f'"{w:010b}"' for w in words[i:i + 8]))
print(',\n'.join(lines) + ',')
print('''        others => (others => '0'));

end package lcd_font_pkg;''')
